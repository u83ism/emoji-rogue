import { buildCatalogMarkdown } from "./catalog.js";

// Builds demo/catalog.html — the web page twin of docs/catalog.md — by
// converting buildCatalogMarkdown()'s output, so both are always the same
// data. Only the Markdown subset that generator emits is understood:
// `#`/`##` headings, one-line paragraphs, pipe tables, inline `code`, and
// the HTML generated-file comment. Freshness is enforced the same way as the
// Markdown (catalogHtml.test.ts); regenerate with `npm run docs:catalog`.

const escapeHtml = (text: string): string =>
	text
		.replaceAll("&", "&amp;")
		.replaceAll("<", "&lt;")
		.replaceAll(">", "&gt;")
		.replaceAll('"', "&quot;");

/** Escapes `text` and turns `code` spans into <code>. */
const formatInline = (text: string): string =>
	escapeHtml(text).replaceAll(/`([^`]+)`/g, "<code>$1</code>");

const splitTableRow = (line: string): readonly string[] =>
	line
		.slice(1, -1)
		.split("|")
		.map((cell) => cell.trim());

const formatTable = (lines: readonly string[]): string => {
	const [header = "", , ...rows] = lines;
	const headerCells = splitTableRow(header)
		.map((cell) => `<th>${formatInline(cell)}</th>`)
		.join("");
	const bodyRows = rows
		.map(
			(row) =>
				`<tr>${splitTableRow(row)
					.map((cell) => `<td>${formatInline(cell)}</td>`)
					.join("")}</tr>`,
		)
		.join("\n");
	return `<div class="table-scroll"><table>\n<thead><tr>${headerCells}</tr></thead>\n<tbody>\n${bodyRows}\n</tbody>\n</table></div>`;
};

/** The catalog Markdown's blocks (separated by blank lines) as HTML. */
const formatBlocks = (markdown: string): readonly string[] =>
	markdown
		.split("\n\n")
		.map((block) => block.trim())
		.filter((block) => block !== "" && !block.startsWith("<!--"))
		.map((block) => {
			if (block.startsWith("## ")) {
				const title = block.slice(3);
				return `<h2 id="${escapeHtml(title)}">${formatInline(title)}</h2>`;
			}
			if (block.startsWith("# ")) {
				return `<h1>${formatInline(block.slice(2))}</h1>`;
			}
			if (block.startsWith("|")) {
				return formatTable(block.split("\n"));
			}
			return `<p>${formatInline(block)}</p>`;
		});

const formatNavigation = (markdown: string): string =>
	markdown
		.split("\n")
		.filter((line) => line.startsWith("## "))
		.map((line) => {
			const title = escapeHtml(line.slice(3));
			return `<a href="#${title}">${title}</a>`;
		})
		.join("\n");

/** The complete demo/catalog.html content. */
export const buildCatalogHtml = (): string => {
	const markdown = buildCatalogMarkdown();
	return `<!doctype html>
<!-- GENERATED by scripts/generate-catalog.ts — 手で編集しない。更新は npm run docs:catalog -->
<html lang="ja">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>カタログ — 絵文字ローグ</title>
<meta name="description" content="絵文字ローグの敵・アイテム・罠の全一覧。数値は原作Rogue 5.4のまま。" />
<link rel="stylesheet" href="./catalog.css" />
</head>
<body>
<header class="site-header">
<a class="site-title" href="./">絵文字ローグ</a>
<nav class="site-nav"><a href="./">▶ 遊ぶ</a><a href="./catalog.html" aria-current="page">カタログ</a></nav>
</header>
<main>
<nav class="toc">
${formatNavigation(markdown)}
</nav>
${formatBlocks(markdown).join("\n")}
</main>
</body>
</html>
`;
};
